/**
 * Generate a TypeScript file that exports the SQL migration content as strings.
 *
 * Why: The original `migrations-loader.ts` reads SQL files at runtime via
 * `readFileSync(join(__dirname, 'migrations/...'))`. When esbuild bundles the
 * Vercel serverless function, it inlines the .ts code but NOT the .sql files —
 * the runtime `readFileSync` then fails (ENOENT) because Vercel deploys only
 * the bundled .mjs, not the .sql files alongside.
 *
 * This script generates `migrations-generated.ts` with the SQL content inlined
 * as string exports. esbuild then bundles this .ts file into the .mjs bundle,
 * so no runtime file reads are needed.
 *
 * For local dev (vitest/Bun): the generated file is committed to the repo, so
 * vitest imports it directly (no .sql loader plugin needed).
 *
 * Run this whenever a .sql migration file is modified.
 */

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const ROOT = path.resolve(fileURLToPath(import.meta.url), '..', '..')
const MIGRATIONS_DIR = path.join(ROOT, 'packages', 'contractor-core', 'src', 'persistence', 'migrations')
const OUTPUT = path.join(ROOT, 'packages', 'contractor-core', 'src', 'persistence', 'migrations-generated.ts')

const MIGRATIONS = [
  ['FOUNDATION_MIGRATION_SQL', '0001_foundation.sql'],
  ['COMMERCIAL_MIGRATION_SQL', '0002_commercial.sql'],
  ['MAGIC_LINKS_MIGRATION_SQL', '0003_magic_links.sql'],
  ['AUTH_MIGRATION_SQL', '0004_auth.sql'],
]

async function main() {
  const lines = [
    '/**',
    ' * AUTO-GENERATED by scripts/inline-migrations.mjs — do not edit.',
    ' *',
    ' * Exports the SQL migration content as strings so esbuild can inline them',
    ' * into the Vercel serverless bundle (no runtime readFileSync needed).',
    ' * Regenerate with: `bun run inline:migrations`',
    ' */',
    '',
  ]

  for (const [exportName, filename] of MIGRATIONS) {
    const sqlPath = path.join(MIGRATIONS_DIR, filename)
    const sql = await readFile(sqlPath, 'utf8')
    lines.push(`export const ${exportName} = ${JSON.stringify(sql)};`)
    lines.push('')
  }

  await writeFile(OUTPUT, lines.join('\n'), 'utf8')
  console.log(`Generated: ${OUTPUT.replace(ROOT, '.')}`)
  console.log(`  ${MIGRATIONS.length} migrations inlined`)
}

main().catch(err => {
  console.error('Generation failed:', err)
  process.exit(1)
})
